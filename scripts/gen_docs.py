"""Generate docs/PARAMETERS.md and docs/METRICS.md from code (single source of truth)."""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from caterya.core.config import CateryaConfig
from caterya.core.registry import list_metrics
from caterya.profiles.pillars import PILLAR_MAP
from caterya.profiles.registry import PROFILES

D = Path(__file__).resolve().parent.parent / "docs"


def params() -> str:
    g = defaultdict(list)
    for p in CateryaConfig.describe():
        g[p["group"]].append(p)
    out = ["# Parameters", "", "_Generated by `scripts/gen_docs.py`. Every parameter can be set via environment variable, `CateryaConfig(...)`, or JSON._", ""]
    for grp, ps in g.items():
        out += [f"## {grp}", "", "| Environment variable | Default | Meaning |", "|---|---|---|"]
        out += [f"| `{p['env']}` | `{json.dumps(p['default'])}` | {p['help']} |" for p in ps] + [""]
    out += ["## Profile thresholds", "", "Thresholds are **defaults to be replaced by the deployer's own risk appetite**.", "",
            "| Profile | Metric | min (hard) | warn | required |", "|---|---|---|---|---|"]
    for p in PROFILES.values():
        out += [f"| {p.id} | `{m.metric_id}` | {m.min_value if m.min_value is not None else '—'} | {m.warn if m.warn is not None else '—'} | {'yes' if m.required and not m.info else 'no'} |" for m in p.plans]
    return "\n".join(out) + "\n"


def metrics() -> str:
    out = ["# Metric specifications", "",
           "_Generated from `MetricSpec` objects. The spec hash is embedded in every Evidence record, so a change of definition is detectable._", "",
           "All `score` metrics are normalised to [0,1], **higher = more trustworthy**. Status: `stable` < `experimental` < `research`.", ""]
    for s in sorted(list_metrics(), key=lambda x: (x.domain.value, x.id)):
        out += [f"## `{s.id}` — {s.title}", "", f"- **Domain:** {s.domain.value} · **Status:** {s.status} · **Access:** {s.access} · **Kind:** {s.kind} ({s.unit})",
                f"- **Pillar / Golden-Triangle term:** {s.pillar or '—'} / {s.golden or '—'}", f"- **Description:** {s.description}",
                f"- **Formula:** `{s.formula}`", f"- **Spec hash:** `{s.spec_hash()}`"]
        if s.assumptions:
            out += ["- **Assumptions:**"] + [f"  - {a}" for a in s.assumptions]
        out += ["- **Limitations:**"] + [f"  - {a}" for a in s.limitations] + [""]
    out += ["## Pillar map (labels, not scores)", "",
            "Framework 3.0 pillar names are documentation labels on v1.0 domains. They do not add a metric.", ""]
    for key, spec in PILLAR_MAP.items():
        metrics = ", ".join(f"`{m}`" for m in spec["metrics"])
        out += [f"### {key}", "", f"- **Framework 3.0 name:** {spec['framework_3']}", f"- **v1 domain:** {spec['v1_domain']}",
                f"- **Metrics:** {metrics}", f"- **Note:** {spec['note']}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    (D / "PARAMETERS.md").write_text(params())
    (D / "METRICS.md").write_text(metrics())
    print("docs/PARAMETERS.md, docs/METRICS.md written")
