class CateryaError(Exception):
    """Base error."""

class ConfigError(CateryaError): ...
class VerificationError(CateryaError): ...
class PolicyViolation(CateryaError):
    def __init__(self, message: str, reasons=None):
        super().__init__(message)
        self.reasons = list(reasons or [])
class CapabilityUnavailable(CateryaError): ...
class AdapterError(CateryaError): ...
class GovernanceError(CateryaError): ...
